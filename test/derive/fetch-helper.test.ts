    const src = ZZ_BOTH_WRITE.replace("`ZZ Both ${String", "`ZZ Other ${String");
    expect(src).not.toBe(ZZ_BOTH_WRITE);
    expect(runWrite(src).fields?.serviceLabel).toBe("ZZ Other");

