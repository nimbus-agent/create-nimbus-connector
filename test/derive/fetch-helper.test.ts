  '    headers: { ...headers(), "Content-Type": "application/json" },',
  "    ...(body === undefined ? {} : { body }),",
  "  });",
  "  const text = await res.text();",
  "  if (!res.ok) {",
  "    throw new Error(`ZZ Both ${String(res.status)}: ${text.slice(0, 400)}`);",
